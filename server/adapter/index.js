import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { SimulatedAdapter } from './simulated.js';
import { DockerAdapter } from './docker.js';
import { HostedAdapter } from './hosted.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

// T-314: when TWIN_TENANT_ENABLED=true on the TWIN nodes (the current
// deployment), every REST call needs an `x-api-key` header. The key is
// captured by `wallets.mjs anchor` (from `tenant-create`'s JSON output)
// and persisted at data/tenant-state.json. Resolution order:
//   1. process.env.TWIN_<NODE>_API_KEY  (CI / hosted overrides)
//   2. tenant-state.json:nodes.<node>.tenantApiKey
//   3. undefined  (single-tenant mode — KitsuneClient skips the header)
function resolveTenantApiKey(nodeId) {
  const envKey = process.env[`TWIN_${nodeId.toUpperCase()}_API_KEY`];
  if (envKey) return envKey;
  try {
    const raw = fs.readFileSync(path.join(ROOT, 'data', 'tenant-state.json'), 'utf8');
    return JSON.parse(raw)?.nodes?.[nodeId]?.tenantApiKey ?? undefined;
  } catch {
    return undefined;
  }
}

// T-324: the url-transformer encrypted tenant token that gates the node's DSP
// data-plane (/dataspace/inbox + entity reads). Generated by the node's
// `tenant-token` CLI and persisted at tenant-state.json:nodes.<node>.encTenantToken.
// Resolution order: env override, then tenant-state.json, then undefined
// (KitsuneClient then omits the query param — fine for non-DSP modes).
function resolveTenantToken(nodeId) {
  const envTok = process.env[`TWIN_${nodeId.toUpperCase()}_ENC_TENANT_TOKEN`];
  if (envTok) return envTok;
  try {
    const raw = fs.readFileSync(path.join(ROOT, 'data', 'tenant-state.json'), 'utf8');
    return JSON.parse(raw)?.nodes?.[nodeId]?.encTenantToken ?? undefined;
  } catch {
    return undefined;
  }
}

// T-316: under the tenant-per-org model, each org is provisioned as its own
// TWIN tenant with its own api-key + node user, persisted by
// `wallets.mjs provision-orgs` at tenant-state.json:orgs.<node>.<orgId>.
// Returns { orgDid, tenantId, tenantApiKey, address, email, password } or null
// for orgs not provisioned this way (REST-created, one-tenant-per-node). Used
// by the seed and by boot hydration so per-org attestation requests carry the
// org's own tenant key (its user lives in its own tenant — login needs it).
export function resolveOrgTenant(nodeId, orgId) {
  try {
    const raw = fs.readFileSync(path.join(ROOT, 'data', 'tenant-state.json'), 'utf8');
    return JSON.parse(raw)?.orgs?.[nodeId]?.[orgId] ?? null;
  } catch {
    return null;
  }
}

export { ITwinAdapter, ITWIN_ADAPTER_METHODS } from './base.js';
export { SimulatedAdapter, DockerAdapter, HostedAdapter };

const VALID_MODES = ['simulated', 'docker', 'hosted'];

// Default mode targets the local Docker TWIN Nodes. Override with ADAPTER_MODE.
export const ADAPTER_DEFAULT_MODE = 'docker';

// Per-node localhost ports for Docker mode (default twin-node-alpha=3000, twin-node-beta=3001).
const DOCKER_DEFAULT_PORT = { alpha: 3000, beta: 3001 };

// Demo credentials baked into twin/{alpha,beta}/bootstrap.env. Override at deploy time.
const DEMO_PASSWORD = { alpha: 'TwinAlpha#2026!Demo', beta: 'TwinBeta#2026!Demo' };

export function resolveAdapterMode() {
  const mode = process.env.ADAPTER_MODE || ADAPTER_DEFAULT_MODE;
  if (!VALID_MODES.includes(mode)) {
    throw new Error(`Invalid ADAPTER_MODE=${mode}. Expected one of: ${VALID_MODES.join(', ')}.`);
  }
  return mode;
}

// Resolve the per-node connection config from environment variables.
// nodeId is 'alpha' or 'beta' (matches NODE_ID in server/store.js).
export function resolveAdapterConfig(mode, nodeId) {
  if (mode === 'simulated') return {};
  const upper = nodeId.toUpperCase();
  const envUrl      = process.env[`TWIN_${upper}_URL`];
  const envEmail    = process.env[`TWIN_${upper}_EMAIL`];
  const envPassword = process.env[`TWIN_${upper}_PASSWORD`];

  if (mode === 'hosted' && !envUrl) {
    throw new Error(`hosted mode requires TWIN_${upper}_URL to be set (no localhost default).`);
  }

  const port = DOCKER_DEFAULT_PORT[nodeId];
  return {
    nodeUrl:  envUrl ?? (mode === 'docker' && port ? `http://localhost:${port}` : undefined),
    email:    envEmail ?? `admin@${nodeId.toLowerCase()}`,
    password: envPassword ?? DEMO_PASSWORD[nodeId] ?? 'changeme',
    apiKey:   resolveTenantApiKey(nodeId),
    encTenantToken: resolveTenantToken(nodeId),
  };
}

// The demo's two corridor nodes.
const KNOWN_NODES = ['alpha', 'beta'];

// DSP cross-node federation: resolve connection configs for the OTHER node(s)
// so the adapter can deliver a Dataspace-Protocol data-plane notify to the
// RECIPIENT's node (the consumer side of a federated share). Docker mode only
// — both demo nodes are local; hosted mode would need explicit peer URLs.
function resolvePeers(mode, nodeId) {
  if (mode !== 'docker') return {};
  const peers = {};
  for (const other of KNOWN_NODES) {
    if (other === nodeId) continue;
    peers[other] = resolveAdapterConfig(mode, other);
  }
  return peers;
}

// Which node hosts a given org (from tenant-state.json orgs.<node>.<orgId>).
// Used to route a federated share's notify to the recipient org's node.
export function resolveOrgNode(orgId) {
  try {
    const raw = fs.readFileSync(path.join(ROOT, 'data', 'tenant-state.json'), 'utf8');
    const orgs = JSON.parse(raw)?.orgs ?? {};
    for (const [node, map] of Object.entries(orgs)) {
      if (map && Object.prototype.hasOwnProperty.call(map, orgId)) return node;
    }
  } catch { /* tenant-state absent (simulated) — caller falls back to local */ }
  return null;
}

// Factory: returns an uninitialised adapter for the requested mode.
export function createAdapter(mode = ADAPTER_DEFAULT_MODE) {
  switch (mode) {
    case 'simulated': return new SimulatedAdapter();
    case 'docker':    return new DockerAdapter();
    case 'hosted':    return new HostedAdapter();
    default:
      throw new Error(`Unknown adapter mode: ${mode}. Expected ${VALID_MODES.join(', ')}.`);
  }
}

// Create + init in one shot. Reads env vars to derive config when not provided.
// nodeId selects which TWIN_<NODE>_* env block to use.
export async function createAndInitAdapter(mode, nodeId, configOverrides = {}) {
  const config = {
    ...resolveAdapterConfig(mode, nodeId),
    nodeId,
    // DSP cross-node federation plumbing (injected to avoid a circular import
    // back into this module from the adapter).
    peers: resolvePeers(mode, nodeId),
    resolveOrgNode,
    resolveOrgTenant,
    ...configOverrides,
  };
  const adapter = createAdapter(mode);
  await adapter.init(config);
  return adapter;
}
